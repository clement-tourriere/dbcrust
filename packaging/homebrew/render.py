#!/usr/bin/env python3
"""Render the Homebrew formula (CLI) and cask (desktop app) of a release.

    python3 packaging/homebrew/render.py --version 0.40.0 --assets DIR --tap DIR

--assets holds the release's `.sha256` files (`<hash>  <file name>`, as the
build jobs write them). Writes into the tap checkout:

- `Formula/dbcrust.rb` from the CLI archives (fails if one is missing);
- `Casks/dbcrust-gui.rb` from the notarized DMG, when the release has one
  (an unsigned DMG is never published, so there is no cask until macOS
  signing is on: see packaging/macos/README.md).

A file that already describes a newer version is left alone, so re-running an
older release never downgrades the tap.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HOMEPAGE = "https://clement-tourriere.github.io/dbcrust/"
DMG = "DBCrust-macos-universal.dmg"
# Linux x86_64 takes the static musl build: the glibc one needs the glibc of
# the CI image, newer than the one Homebrew on Linux may provide.
FORMULA_ARCHIVES = {
    ("macos", "arm"): "dbcrust-aarch64-apple-darwin.tar.gz",
    ("macos", "intel"): "dbcrust-x86_64-apple-darwin.tar.gz",
    ("linux", "arm"): "dbcrust-aarch64-unknown-linux-gnu.tar.gz",
    ("linux", "intel"): "dbcrust-x86_64-unknown-linux-musl.tar.gz",
}


def version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def write_unless_newer(path: Path, content: str, version: str) -> bool:
    """Write `content` unless `path` already has a newer `version "X.Y.Z"`."""
    if path.exists():
        found = re.search(
            r'^\s*version "(\d+\.\d+\.\d+)"', path.read_text(), re.MULTILINE
        )
        if found and version_key(found.group(1)) > version_key(version):
            print(
                f"{path.parent.name}/{path.name} has {found.group(1)}, newer than {version}: left alone"
            )
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return True


def read_checksums(assets: Path) -> dict[str, str]:
    sums = {}
    for path in sorted(assets.rglob("*.sha256")):
        for line in path.read_text().splitlines():
            parts = line.split()
            if len(parts) == 2 and re.fullmatch(r"[0-9a-f]{64}", parts[0]):
                sums[parts[1].lstrip("*")] = parts[0]
    return sums


def formula(version: str, repo: str, sums: dict[str, str]) -> str:
    base = f"https://github.com/{repo}/releases/download/v{version}"

    def archive(os_name: str, cpu: str) -> str:
        name = FORMULA_ARCHIVES[(os_name, cpu)]
        return (
            f"    on_{cpu} do\n"
            f'      url "{base}/{name}"\n'
            f'      sha256 "{sums[name]}"\n'
            f"    end\n"
        )

    return f"""# Generated by packaging/homebrew/render.py in {repo}: do not edit by hand.
class Dbcrust < Formula
  desc "Fast multi-engine database client for the terminal"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
{archive("macos", "arm")}{archive("macos", "intel")}  end

  on_linux do
{archive("linux", "arm")}{archive("linux", "intel")}  end

  def install
    bin.install "dbcrust", "dbc", "dbcrust-agent"
    generate_completions_from_executable(bin/"dbcrust", "--completions")
    generate_completions_from_executable(bin/"dbc", "--completions")
  end

  test do
    assert_match "dbcrust #{{version}}", shell_output("#{{bin}}/dbcrust --version")
  end
end
"""


def cask(version: str, repo: str, sha256: str) -> str:
    return f"""# Generated by packaging/homebrew/render.py in {repo}: do not edit by hand.
cask "dbcrust-gui" do
  version "{version}"
  sha256 "{sha256}"

  url "https://github.com/{repo}/releases/download/v#{{version}}/{DMG}",
      verified: "github.com/{repo}/"
  name "DBCrust"
  desc "Native database workbench for PostgreSQL, MySQL, SQLite and more"
  homepage "{HOMEPAGE}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: :monterey

  app "DBCrust.app"

  # ~/.config/dbcrust is shared with the CLI: only the app's own state goes
  zap trash: [
    "~/.config/dbcrust/gui_state.toml",
    "~/Library/Saved Application State/com.dbcrust.gui.savedState",
  ]
end
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--version", required=True, help="release version, without the v"
    )
    parser.add_argument(
        "--assets", required=True, type=Path, help="directory with the .sha256 files"
    )
    parser.add_argument(
        "--tap", required=True, type=Path, help="checkout of the tap repository"
    )
    parser.add_argument(
        "--repo",
        default="clement-tourriere/dbcrust",
        help="GitHub repository of the releases",
    )
    args = parser.parse_args()

    version = args.version.removeprefix("v")
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        parser.error(f"{args.version!r} is not a stable release version (X.Y.Z)")

    sums = read_checksums(args.assets)
    missing = [name for name in FORMULA_ARCHIVES.values() if name not in sums]
    if missing:
        print(
            f"error: no checksum for {', '.join(missing)} in {args.assets}",
            file=sys.stderr,
        )
        return 1

    written = []
    if write_unless_newer(
        args.tap / "Formula" / "dbcrust.rb", formula(version, args.repo, sums), version
    ):
        written.append("Formula/dbcrust.rb")
    if DMG not in sums:
        print(f"no {DMG} in this release (macOS signing off): cask not updated")
    elif write_unless_newer(
        args.tap / "Casks" / "dbcrust-gui.rb",
        cask(version, args.repo, sums[DMG]),
        version,
    ):
        written.append("Casks/dbcrust-gui.rb")

    print(f"dbcrust {version}: wrote {', '.join(written) or 'nothing'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
